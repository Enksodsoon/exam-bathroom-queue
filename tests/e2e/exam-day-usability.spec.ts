import {test,expect} from '@playwright/test';
test('repeatable controller and proctor journeys',async({browser})=>{
 const ctrl=await browser.newContext({viewport:{width:1280,height:900}});
 const p=await ctrl.newPage(); await p.goto('/');
 await expect(p.getByRole('heading',{name:'Bathroom Queue'})).toBeVisible();
 await p.getByRole('button',{name:'Create Exam Session'}).click();
 await expect(p.getByTestId('window-status-badge')).toBeVisible();
 await p.getByRole('button',{name:'Exam Timer Settings'}).click();
 await p.getByRole('button',{name:'Set Start = Now'}).click();
 await p.locator('#exam-duration-minutes').fill('90');
 await p.locator('#exam-clock-offset').fill('35');
 await p.getByRole('button',{name:'Save Exam Config'}).click();
 await expect(p.getByText('Timer saved.')).toBeVisible();
 await p.getByRole('button',{name:'Share QR Code'}).click();
 const invite=await p.getByRole("textbox",{name:"Staff Join Link"}).inputValue();
 const staff=await browser.newContext({viewport:{width:390,height:844}});
 const s=await staff.newPage(); await s.goto(invite);
 await expect(s.getByRole('heading',{name:'Staff Check-In'})).toBeVisible();
 await s.locator('#staff-label-input').fill('Hall A');
 await s.getByRole('button',{name:'Join Session'}).click();
 await expect(s.getByRole('button',{name:'Hall A'})).toBeVisible();
 await s.getByRole('button',{name:'Male',exact:true}).click();
 await s.locator('#staff-student-number').fill('SYN01');
 await s.getByRole('button',{name:'Submit Student'}).click();
 await expect(s.getByRole('status').filter({hasText:'SYN01'})).toBeVisible();
 await staff.setOffline(true);
 await expect(s.getByTestId('sync-stale-badge')).toBeVisible({timeout:18000});
 await expect(s.getByTestId("next-student-alert")).toHaveCount(0,{timeout:2500});
 await staff.setOffline(false);
 await expect(s.getByTestId('sync-stale-badge')).toHaveCount(0,{timeout:18000});
 const row=p.getByTestId('queue-column-M').locator('li[data-student-number="SYN01"]');
 await row.getByRole('button',{name:'Enter Bathroom'}).click();
 await expect(p.getByTestId('occupancy-M').getByText('#SYN01')).toBeVisible();
 await p.getByTestId('occupancy-M').getByRole('button',{name:'Mark Returned'}).click();
 await expect(p.getByTestId('occupancy-M').getByText('Vacant',{exact:true})).toBeVisible();
 await p.getByRole('button',{name:'Clear Session'}).click(); await p.getByRole('button',{name:'Confirm Clear'}).click();
 await expect(p.getByTestId('queue-column-M').getByText('Empty queue')).toBeVisible();
 await staff.close();await ctrl.close();
});
test('setup points to timer, paste retains invitation, and reconnect protects draft',async({page,browser})=>{
 await page.goto('/'); await page.getByRole('button',{name:'Create Exam Session'}).click();
 await expect(page.getByTestId('window-status-badge')).toBeVisible();
 const timerGuide=page.getByRole('button',{name:'Set exam timer',exact:true});
 await expect(timerGuide).toBeVisible({timeout:3000}); await timerGuide.click();
 await page.getByRole('button',{name:'Set Start = Now'}).click();
 await page.locator('#exam-duration-minutes').fill('90'); await page.locator('#exam-clock-offset').fill('35');
 await page.getByRole('button',{name:'Save Exam Config'}).click();
 const guideInvite=page.getByRole('button',{name:'Invite proctors',exact:true});
 await expect(guideInvite).toBeVisible();await guideInvite.click();
 const link=await page.getByRole('textbox',{name:'Staff Join Link'}).inputValue();
 const ctx=await browser.newContext();const s=await ctx.newPage();
 await s.goto('/');await s.locator('#join-session-input').fill(link);
 await s.getByRole('button',{name:'Join Session'}).click();
 await expect.poll(()=>new URL(s.url()).searchParams.get('invite')).toBe(new URL(link).searchParams.get('invite'));
 await s.locator('#staff-label-input').fill('Hall B');await s.getByRole('button',{name:'Join Session'}).click();
 const field=s.locator('#staff-student-number'); const submit=s.getByRole('button',{name:'Submit Student'});
 await field.fill('DRAFT1');await ctx.setOffline(true);
 await expect(s.getByTestId('staff-reconnect-help')).toBeVisible({timeout:18000});await expect(submit).toBeDisabled();await expect(field).toHaveValue('DRAFT1');
 await ctx.setOffline(false); await expect(submit).toBeEnabled({timeout:18000});await expect(field).toHaveValue('DRAFT1');
 await expect(page.getByRole('button',{name:'Invite proctors',exact:true})).toHaveCount(0);
 await submit.click();await expect(s.getByRole('status').filter({hasText:'DRAFT1'})).toBeVisible();
 await ctx.close();
});
